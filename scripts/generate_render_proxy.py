#!/usr/bin/env python3
"""Generate typed GL command wrappers and fail on uncovered runtime symbols."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parent.parent
out=root/'build/render-thread-stage';out.mkdir(parents=True,exist_ok=True)
apis=[]
for file in ['probe/gl_cost_calls.def','probe/render_thread_extra.def']:
 for line in (root/file).read_text().splitlines():
  if line.startswith('V('):kind='void';body=line[2:-1]
  elif line.startswith('R('):kind,body=line[2:-1].split(',',1)
  else:continue
  m=re.fullmatch(r'(gl\w+),\((.*)\),\((.*)\)',body)
  if not m:raise SystemExit('Bad wrapper definition '+line)
  name,params,args=m.groups();args=args.split(',') if args else []
  declarations=params.split(',') if params!='void' else []
  if len(args)!=len(declarations):raise SystemExit('Argument mismatch '+name)
  apis.append((name,kind,params,args,declarations))
names={a[0] for a in apis}
if len(names)!=len(apis):raise SystemExit('Duplicate GL wrappers')
required=set()
for f in ['runtime/d3d8.c','runtime/d3d8_renderer.c','runtime/fps_overlay.c']:
 required.update(re.findall(r'\b(gl[A-Z]\w*)\s*\(', (root/f).read_text()))
if required-names:raise SystemExit('Uncovered GL calls: '+str(sorted(required-names)))
lines=['/* Generated by scripts/generate_render_proxy.py; do not edit. */']
enum=['enum { OP_PAD=0,OP_NATIVE_JOB,OP_DRAW_CHECK,OP_BARRIER,']
enum += [' OP_'+a[0]+',' for a in apis];enum+=[' OP_COUNT };']
lines+=enum
lines+=['static const char *const op_names[OP_COUNT]={"padding","native-job","draw-error-check","barrier",']
lines+=[' "'+a[0]+'",' for a in apis];lines+=['};']
(out/'render_proxy_ops.inc').write_text('\n'.join(lines)+'\n')
lines=[]
for name,ret,params,args,decl in apis:
 fields=';'.join(decl)+(';' if decl else '')
 if ret!='void':fields+=ret+' *result;'
 if not fields:fields='int unused;'
 call=','.join('a->'+x for x in args)
 lines += [f'extern {ret} __real_{name}({params});',f'typedef struct {{ {fields} }} Args_{name};',f'static void exec_{name}(void *p){{Args_{name} *a=p;'+(f'*a->result=' if ret!='void' else '')+f'__real_{name}({call});'+(' (void)a;' if not args and ret=='void' else '')+'}']
 lines += [f'{ret} __wrap_{name}({params}){{',f' if(!proxy_active()||worker_thread)'+('{__real_'+name+'('+','.join(args)+');return;}' if ret=='void' else 'return __real_'+name+'('+','.join(args)+');')]
 if ret!='void':lines += [f' {ret} result=0;']
 init=','.join('.'+n+'='+n for n in args)
 if ret!='void':init+=(',' if init else '')+'.result=&result'
 lines += [f' Args_{name} _rt_args={{'+(init if init else '0')+'};']
 if name in ('glDrawArrays','glDrawElements'):lines += [f' producer_last_draw_op=OP_{name};']
 sync=ret!='void' or name.startswith(('glGet','glGen')) or name in ('glReadPixels','glFinish','glShaderSource','glBindAttribLocation')
 copy=None;guard='0'
 if name in ('glBufferData','glBufferSubData'):copy=('data','(size_t)size');guard='size<0'
 elif name.startswith('glUniform') and args and args[-1]=='value':
  factor=9 if name=='glUniformMatrix3fv' else 16 if name=='glUniformMatrix4fv' else int(re.search(r'Uniform(\d)',name)[1])
  copy=('value',f'(size_t)count*{factor}*sizeof(GLfloat)');guard='count<0'
 elif name.startswith('glDelete') and 'n' in args:copy=(args[-1],'(size_t)n*sizeof(GLuint)');guard='n<0'
 elif name in ('glTexImage2D','glTexSubImage2D'):
  lines+=[' size_t pixel_bytes=0;int borrow=texture_payload(width,height,format,type,&pixel_bytes);']
  copy=('pixels','pixel_bytes');guard='borrow'
 if copy:
  pointer,size=copy
  lines += [f' int force_sync=({guard});',f' issue(exec_{name},OP_{name},&_rt_args,sizeof _rt_args,{pointer},force_sync?0:{size},offsetof(Args_{name},{pointer}),force_sync);']
 else:
  sync_expr='client_arrays()||!proxy_element_buffer' if name=='glDrawElements' else 'client_arrays()' if name=='glDrawArrays' else str(int(sync))
  lines += [f' issue(exec_{name},OP_{name},&_rt_args,sizeof _rt_args,NULL,0,SIZE_MAX,{sync_expr});']
 if name=='glPixelStorei':lines+=[' if(pname==GL_UNPACK_ALIGNMENT)proxy_unpack_alignment=param;',' if(pname==0x0cf2)proxy_unpack_row_length=param;',' if(pname==0x0cf3)proxy_unpack_skip_rows=param;',' if(pname==0x0cf4)proxy_unpack_skip_pixels=param;']
 if name=='glBindBuffer':lines+=[' if(target==0x88ec)proxy_unpack_buffer=buffer;',' if(target==GL_ARRAY_BUFFER)proxy_array_buffer=buffer;',' if(target==GL_ELEMENT_ARRAY_BUFFER)proxy_element_buffer=buffer;']
 if name=='glDeleteBuffers':lines+=[' if(n>0&&buffers)for(GLsizei i=0;i<n;i++)deleted_buffer(buffers[i]);']
 if name=='glEnableVertexAttribArray':lines+=[' attribute_shadow(index,1,0);']
 if name=='glDisableVertexAttribArray':lines+=[' attribute_shadow(index,0,0);']
 if name=='glVertexAttribPointer':lines+=[' attribute_pointer_shadow(index,size,type,stride,pointer);']
 if ret!='void':lines+=[' return result;']
 lines+=['}']
(out/'render_proxy_wrappers.inc').write_text('\n'.join(lines)+'\n')
(out/'wrap-flags.txt').write_text(' '.join('-Wl,--wrap='+x for x in sorted(names|{'SDL_GL_SwapWindow','SDL_GL_SetSwapInterval'}))+'\n')
(out/'api-inventory.json').write_text(json.dumps({'required':sorted(required),'wrapped':sorted(names),'SDL':['SDL_GL_SwapWindow','SDL_GL_SetSwapInterval'],'missing':sorted(required-names)},indent=2)+'\n')
print(f'Generated {len(apis)} typed GL wrappers; all {len(required)} runtime GL symbols covered')
